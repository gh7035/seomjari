export interface IslandPoly { id: string; coords: [number, number][]; elevation: number }

// 한라산을 중심으로 한 동심 타원 → 계단형 지형 (전부 같은 색 쓰여 하나의 3D 면으로 보임)
const HALLASAN_CENTER: [number, number] = [126.5325, 33.3617]
const KM_PER_DEG_LON = 1 / 93  // ≈ 0.01075
const KM_PER_DEG_LAT = 1 / 111 // ≈ 0.009
function ellipse(cx: number, cy: number, rxKm: number, ryKm: number, n = 56): [number, number][] {
  const pts: [number, number][] = []
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2
    pts.push([cx + Math.cos(a) * rxKm * KM_PER_DEG_LON, cy + Math.sin(a) * ryKm * KM_PER_DEG_LAT])
  }
  pts.push(pts[0])
  return pts
}

